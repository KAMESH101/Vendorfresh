// Asynchronous fetch wrapper to retrieve products from the database (or fallback locally)
export const getProducts = async () => {
  if (isMockClient) {
    return { data: staticProducts, error: null };
  }
  const { data, error } = await supabase.from('products').select('*');
  return { data, error };
};

